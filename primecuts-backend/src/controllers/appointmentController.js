// Pull confirmed bookings for frontend UI
const getAppointments = async (req, res) => {
  try {
    const { date } = req.query;
    // Express parses bracket notation (e.g. ?date[$ne]=x) into an object, which Mongo would then
    // read as a query operator instead of a literal value — reject anything that isn't a plain string.
    if (date !== undefined && typeof date !== "string") {
      return res.status(400).json({ success: false, error: "Invalid date." });
    }

    const query = { status: { $in: ["pending", "confirmed"] } };
    if (date) query.date = date;

    // Anyone can call this to check open times, so only send back the time, never customer info
    const [appointments, blockedRanges, reservedSlots] = await Promise.all([
      Appointment.find(query).select("date time -_id"),
      date
        ? BlockedTime.find({ date }).select("startTime endTime -_id")
        : Promise.resolve([]),
      // Subscribers' future seats that aren't real appointments yet — shown as taken like any other.
      date ? reservedSlotsOn(date) : Promise.resolve([]),
    ]);
    const data = [...appointments, ...reservedSlots.map((slot) => ({ date, time: slot.time }))];
    res.status(200).json({ success: true, data, blockedRanges });
  } catch (error) {
    res.status(500).json({ success: false, error: "Server Error" });
  }
};

