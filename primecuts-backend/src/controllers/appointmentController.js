// SumUp doesn't sign its webhook payload, so the body can't be trusted for the actual payment
// decision — it's only used to look up which appointment this is about. The real status always
// comes from a fresh GET against SumUp's API using the checkout id WE stored when we created the
// checkout (never one supplied by the caller), so a forged webhook/cancel call can't confirm or
// tamper with a booking. Shared by the webhook and the frontend's return-from-checkout flow, since
// SumUp only offers a single redirect_url for both outcomes and may deliver the webhook late.
const resolveCheckoutStatus = async (appointment) => {
  if (appointment.status === "confirmed") {
    return { status: "confirmed" };
  }

  if (!appointment.sumupCheckoutId) {
    return { status: "error", error: "Appointment has no checkout on record." };
  }

  let checkoutStatus;
  let checkout;
  try {
    checkout = await sumupClient.checkouts.get(appointment.sumupCheckoutId);
    checkoutStatus = String(checkout.status || "").toUpperCase();
  } catch (lookupError) {
    console.error("Unable to verify SumUp checkout:", lookupError.message);
    return { status: "error", error: "Unable to verify SumUp checkout status." };
  }

  if (checkoutStatus !== "PAID") {
    // PENDING just means SumUp hasn't decided yet (e.g. still on 3DS) — leave the hold in place
    // and only release it once SumUp reports a terminal failure so we don't race a late success.
    // A checkout past its own valid_until is also terminal even if SumUp is slow to relabel it as
    // EXPIRED — the payer can no longer complete it, so there's nothing left to wait for.
    const validUntilMs = checkout.valid_until ? new Date(checkout.valid_until).getTime() : null;
    const pastValidity = validUntilMs !== null && Date.now() > validUntilMs;

    if (checkoutStatus === "FAILED" || checkoutStatus === "EXPIRED" || pastValidity) {
      // Conditioned on status still not being "confirmed" so we can never release a booking that
      // another caller (webhook / frontend return / reconciliation sweep) confirmed a moment ago —
      // this is exactly the race that let a paid appointment get silently dropped previously.
      // Marks it "expired" rather than deleting it — this is what makes that failure mode
      // structurally impossible now: the customer's contact info and checkout id survive even if
      // SumUp turns out to have actually settled the payment after this point (the self-healing
      // sweep in server.js re-checks recently-expired ones for exactly that).
      const released = await Appointment.findOneAndUpdate(
        { _id: appointment._id, status: { $ne: "confirmed" } },
        {
          $set: {
            status: "expired",
            releasedReason: checkoutStatus === "FAILED" ? "failed" : pastValidity ? "past_validity" : "expired",
            releasedAt: new Date(),
          },
        },
      );
      if (!released) {
        return { status: "confirmed" };
      }
      return { status: "released", checkoutStatus };
    }
    return { status: "pending", checkoutStatus };
  }

  // Double check race conditions just in case
  const collision = await Appointment.findOne({
    date: appointment.date,
    time: appointment.time,
    status: "confirmed",
    _id: { $ne: appointment._id },
  });

  if (collision) {
    // This appointment genuinely got paid — it just lost a same-slot race to another booking that
    // confirmed first. That's real money with nowhere to go, so this must never be a silent
    // delete: keep the record (marked "expired"/"collision") so an admin can see it and refund or
    // reschedule the customer, instead of the payment just vanishing from every record we have.
    await Appointment.findByIdAndUpdate(appointment._id, {
      $set: { status: "expired", releasedReason: "collision", releasedAt: new Date() },
    });
    return { status: "collision" };
  }

  // Atomically claim the confirmation. The webhook, the frontend's return-from-checkout call, and
  // the reconciliation sweep below can all end up resolving the same appointment around the same
  // time — without this, two of them could both see "not confirmed yet" and both send the customer
  // a duplicate confirmation email and report the same transaction to Branch.nu twice.
  const claimed = await Appointment.findOneAndUpdate(
    { _id: appointment._id, status: { $ne: "confirmed" } },
    { $set: { status: "confirmed" }, $unset: { expiresAt: "" } },
    { new: true },
  );

  if (!claimed) {
    return { status: "confirmed" };
  }

  await Promise.all([
    deliverConfirmationEmail(claimed),
    // Reports the completed transaction to Branch.nu for their revenue-share fee tracking. Never
    // throws — a Branch.nu outage must not affect the customer's already-confirmed payment; it
    // just gets picked up by the retry sweep in server.js instead.
    scheduleBranchReport(claimed, checkout),
  ]);

  return { status: "confirmed" };
};

// Safety net independent of both the webhook and the customer's browser making it back to the
// confirmation page — either of those can fail (stale redirect URL, dropped webhook delivery, the
// customer closing the tab after paying) and, before this existed, that meant a genuinely paid
// appointment could sit as "pending" until an unconditional timer silently deleted it. This sweep
// re-checks every still-pending checkout directly against SumUp so a successful payment always
// gets confirmed even if both of those paths fail. See server.js for the interval it runs on.
const reconcilePendingCheckouts = async () => {
  const pending = await Appointment.find({
    status: "pending",
    sumupCheckoutId: { $exists: true, $ne: null },
  });

  for (const appointment of pending) {
    try {
      const result = await resolveCheckoutStatus(appointment);
      if (result.status === "confirmed") {
        console.log(
          `Reconciliation sweep confirmed appointment ${appointment._id} — the webhook and/or the customer's return-from-checkout call never resolved it.`,
        );
      }
    } catch (error) {
      console.error(`Reconciliation sweep failed for appointment ${appointment._id}:`, error.message);
    }
  }
};

// Self-healing net for the exact failure that lost two real payments before this existed: a
// checkout that SumUp settles as PAID *after* we'd already given up and marked it "expired" (a
// slow 3DS confirmation, a delayed bank callback, or — historically — a broken webhook URL). Only
// looks at recently-released ones so this doesn't grow into an unbounded SumUp-polling job as the
// database ages; anything older than that has long since been handled one way or another.
// Re-checking simply calls resolveCheckoutStatus again, which now either:
//   - finds it's still genuinely unpaid (no-op, re-stamps "expired")
//   - finds it's PAID and the slot is free -> auto-confirms it, exactly as if the webhook had
//     landed on time
//   - finds it's PAID but the slot was since taken by someone else -> stays "expired" with
//     releasedReason "collision", which is real money with a real conflict that needs a human —
//     logged loudly here since there's nothing further this sweep can automate.
const EXPIRED_RECHECK_WINDOW_MS = 7 * 24 * 60 * 60 * 1000;
const reconcileExpiredCheckouts = async () => {
  const cutoff = new Date(Date.now() - EXPIRED_RECHECK_WINDOW_MS);
  const candidates = await Appointment.find({
    status: "expired",
    sumupCheckoutId: { $exists: true, $ne: null },
    releasedAt: { $gte: cutoff },
  });

  for (const appointment of candidates) {
    try {
      const result = await resolveCheckoutStatus(appointment);
      if (result.status === "confirmed") {
        console.log(
          `Self-healing sweep confirmed appointment ${appointment._id} — SumUp settled it as PAID after it had already been marked expired.`,
        );
      } else if (result.status === "collision") {
        console.error(
          "MANUAL FOLLOW-UP REQUIRED:",
          JSON.stringify({
            stage: "expired_checkout_recheck",
            reason: "paid_but_slot_taken",
            appointmentId: appointment._id.toString(),
            customerName: appointment.customerName,
            date: appointment.date,
            time: appointment.time,
          }),
        );
      }
    } catch (error) {
      console.error(`Expired-checkout recheck failed for appointment ${appointment._id}:`, error.message);
    }
  }
};

const findAppointmentForCheckoutNotification = async (body) => {
  const rawAppointmentId =
    body.checkout_reference || body.appointmentId || body.checkoutReference;
  const rawCheckoutId = body.checkout_id || body.checkoutId || body.id;

  // These go straight into a Mongo filter below, so only ever accept plain strings — an object
  // like { "$ne": null } would otherwise be read as a query operator and match arbitrary documents.
  const appointmentId = typeof rawAppointmentId === "string" ? rawAppointmentId : null;
  const checkoutId = typeof rawCheckoutId === "string" ? rawCheckoutId : null;

  if (!appointmentId && !checkoutId) {
    return null;
  }

  const appointmentQuery = [];
  if (appointmentId) {
    if (isValidObjectId(appointmentId)) {
      appointmentQuery.push({ _id: appointmentId });
    }
    appointmentQuery.push({ sumupCheckoutReference: appointmentId });
  }
  if (checkoutId) {
    appointmentQuery.push({ sumupCheckoutId: checkoutId });
  }

  if (appointmentQuery.length === 0) {
    return null;
  }

  return Appointment.findOne({ $or: appointmentQuery });
};

// Step 2: called by the payment provider once payment goes through
const handlePaymentWebhook = async (req, res) => {
  try {
    const body = req.body || {};
    if (!body.checkout_reference && !body.appointmentId && !body.checkoutReference && !body.checkout_id && !body.checkoutId && !body.id) {
      return res.status(400).json({ error: "Missing checkout reference." });
    }

    const appointment = await findAppointmentForCheckoutNotification(body);
    if (!appointment) {
      return res.status(200).json({
        success: true,
        message: "Appointment hold expired or not found.",
      });
    }

    const result = await resolveCheckoutStatus(appointment);
    if (result.status === "error") {
      return res.status(502).json({ error: result.error });
    }

    res.status(200).json({ success: true, message: `Checkout resolved: ${result.status}` });
  } catch (error) {
    console.error("Webhook Error:", error);
    res.status(500).json({ error: "Webhook processing failed" });
  }
};

// Step 3: called by the frontend as soon as the browser returns from SumUp's checkout, so the slot
// frees up right away on a failed/expired payment instead of waiting out the 10-min auto-delete.
const cancelAppointment = async (req, res) => {
  try {
    const { appointmentId } = req.body;
    if (typeof appointmentId !== "string" || !isValidObjectId(appointmentId)) {
      return res.status(400).json({ error: "Missing or invalid appointmentId." });
    }

    const appointment = await Appointment.findById(appointmentId);
    if (!appointment) {
      // Already auto-deleted or never existed, nothing to do
      return res.status(200).json({ success: true, status: "released" });
    }

    const result = await resolveCheckoutStatus(appointment);
    if (result.status === "error") {
      return res.status(502).json({ error: result.error });
    }

    res.status(200).json({ success: true, status: result.status });
  } catch (error) {
    console.error("Cancel Error:", error);
    res.status(500).json({ error: "Cancel processing failed" });
  }
};

// Generates the live WebCal feed for the barber's Apple Calendar (confirmed only)
const getCalendarFeed = async (req, res) => {
  try {
    const appointments = await Appointment.find({ status: "confirmed" });
    const calendar = ical({
      name: "Primecuts Bookings",
      timezone: "Europe/Amsterdam",
    });

    appointments.forEach((app) => {
      const startTime = new Date(`${app.date}T${app.time}:00`);
      const endTime = new Date(startTime.getTime() + 30 * 60000);
      const addOnsText =
        app.addons && app.addons.length > 0 ? app.addons.join(", ") : "None";

      calendar.createEvent({
        start: startTime,
        end: endTime,
        summary: `${app.service} - ${app.customerName}`,
        description: `Customer: ${app.customerName}\nPhone: ${app.customerPhone}\nEmail: ${app.customerEmail}\nAdd-ons: ${addOnsText}\nTotal Price: €${app.totalPrice.toFixed(2)}\nDeposit paid online: €${app.depositAmount.toFixed(2)}\nDue in store: €${(app.totalPrice - app.depositAmount - (app.checkoutFee || 0)).toFixed(2)}`,
        location: "Primecuts Barbershop",
      });
    });

    res.set("Content-Type", "text/calendar; charset=utf-8");
    res.send(calendar.toString());
  } catch (error) {
    res.status(500).send("Error generating calendar feed");
  }
};

