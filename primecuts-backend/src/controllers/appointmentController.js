// The booking form itself constrains these (type="email", required, etc.), but that only holds for
// someone actually using the UI — calling this endpoint directly with garbage/missing values used to
// sail through and only fail at Mongoose's schema validation, surfacing as a generic 500 instead of
// a clean 400. Deliberately lenient (this only guards against nonsense input, not real-world name/
// phone formats), so it never rejects a genuine customer.
const EMAIL_REGEX = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
const PHONE_REGEX = /^[0-9+\-\s()]{6,20}$/;

const DATE_REGEX = /^\d{4}-\d{2}-\d{2}$/;
const isWeekendDate = (dateStr) => {
  const day = new Date(`${dateStr}T00:00:00Z`).getUTCDay();
  return day === 0 || day === 6;
};

// Shared by both booking flows: a real calendar date, not in the past, on a weekday, at one of the
// slot times the booking pages actually offer.
const validateDateTime = (date, time) => {
  if (typeof date !== "string" || !DATE_REGEX.test(date) || Number.isNaN(Date.parse(`${date}T00:00:00Z`))) {
    return "Ongeldige datum of tijd.";
  }
  if (typeof time !== "string" || !isBookableSlotTime(time)) {
    return "Ongeldige datum of tijd.";
  }
  const now = shopNow();
  if (date < now.date) {
    return "Deze datum ligt in het verleden.";
  }
  // Picking 11:00 today at 15:00 — the booking pages list every slot of the day.
  if (date === now.date && time <= now.time) {
    return "Dit tijdstip is vandaag al voorbij. Kies een later tijdstip of een andere dag.";
  }
  if (isWeekendDate(date)) {
    return "We zijn in het weekend gesloten.";
  }
  return null;
};

const validateCustomerFields = ({ customerName, customerEmail, customerPhone }) => {
  if (typeof customerName !== "string" || !customerName.trim() || customerName.trim().length > 100) {
    return "Vul een geldige naam in.";
  }
  if (typeof customerEmail !== "string" || customerEmail.length > 200 || !EMAIL_REGEX.test(customerEmail.trim())) {
    return "Vul een geldig e-mailadres in.";
  }
  if (typeof customerPhone !== "string" || !PHONE_REGEX.test(customerPhone.trim())) {
    return "Vul een geldig telefoonnummer in.";
  }
  return null;
};

// Step 1: create the booking as 'pending' until payment confirms it
const createAppointment = async (req, res) => {
  let createdAppointment = null;

  try {
    const {
      customerName,
      customerEmail,
      customerPhone,
      service,
      addons,
      date,
      time,
    } = req.body;

    const customerFieldError = validateCustomerFields(req.body);
    if (customerFieldError) {
      return res.status(400).json({ error: customerFieldError });
    }

    // date/time feed straight into a Mongo query below — reject anything that isn't a plain string
    // so a crafted object (e.g. { "$ne": null }) can't be read as a query operator. Also enforces
    // the HH:MM shape the blocked-time overlap check below assumes.
    const dateTimeError = validateDateTime(date, time);
    if (dateTimeError) {
      return res.status(400).json({ error: dateTimeError });
    }

    // The frontend already hides slots inside an admin's blocked window, but re-check server-side
    // so it can't be bypassed by calling this endpoint directly.
    const blockedRanges = await BlockedTime.find({ date }).select("startTime endTime -_id");
    if (overlapsBlockedRange(time, blockedRanges)) {
      return res.status(400).json({ error: "Dit tijdslot is niet beschikbaar." });
    }

    // Work out the price ourselves instead of trusting the price sent from the browser
    const servicePrice = SERVICE_PRICES[service];
    if (servicePrice === undefined) {
      return res.status(400).json({ error: "Onbekende behandeling." });
    }

    const addonsList = Array.isArray(addons) ? addons : [];
    let addonsTotal = 0;
    for (const addon of addonsList) {
      const addonPrice = ADDON_PRICES[addon];
      if (addonPrice === undefined) {
        return res.status(400).json({ error: `Onbekende extra: ${addon}` });
      }
      addonsTotal += addonPrice;
    }

    const servicePriceSubtotal = servicePrice + addonsTotal;
    // Charged on top of the deposit, never folded into the in-store balance — but "totalPrice" is
    // the FULL amount the customer pays across both (service + fee), so it's included here.
    const checkoutFee = CHECKOUT_FEE;
    const totalPrice = roundToCents(servicePriceSubtotal + checkoutFee);
    // Customer only pays this much online now; the rest is settled in person at the shop. Based on
    // the service price alone — the fee isn't split, it's paid in full online regardless.
    const depositAmount = roundToCents(servicePriceSubtotal * DEPOSIT_RATIO);
    const amountCharged = roundToCents(depositAmount + checkoutFee);

    // Hold the slot while payment is pending so another customer cannot reserve it. This check is
    // just a fast path for the common case (a clean error without hitting the database's error
    // path) — the actual guarantee against two customers grabbing the same slot is the unique
    // index on (date, time) in the Appointment model, enforced below.
    const existing = await Appointment.findOne({
      date,
      time,
      status: { $in: ["pending", "confirmed"] },
    });

    if (existing?.status === "pending" && existing.customerEmail.trim().toLowerCase() === customerEmail.trim().toLowerCase()) {
      return res.status(409).json({
        error:
          "Je hebt voor deze plek al een betaling gestart. Rond die af, of probeer het over 10 minuten opnieuw als je de betaling hebt afgebroken.",
      });
    }
    if (existing) {
      return res
        .status(400)
        .json({ error: "Dit tijdslot is al bezet. Kies een ander tijdstip." });
    }

    // A subscriber's seat that the renewal sweep hasn't turned into a real appointment yet.
    if (await isReservedBySubscription(date, time)) {
      return res.status(400).json({ error: "Dit tijdslot is al bezet. Kies een ander tijdstip." });
    }

    try {
      createdAppointment = await Appointment.create({
        customerName,
        customerEmail,
        customerPhone,
        service,
        addons,
        date,
        time,
        totalPrice,
        depositAmount,
        checkoutFee,
        status: "pending",
        paymentProvider: "sumup",
      });
    } catch (createError) {
      // Someone else's hold landed on this exact slot between the check above and this insert —
      // the unique index caught it. Same clean response as the pre-check above finding it first.
      if (createError.code === 11000) {
        return res.status(400).json({ error: "Dit tijdslot is al bezet. Kies een ander tijdstip." });
      }
      throw createError;
    }

    if (!process.env.SUMUP_API_KEY || !process.env.SUMUP_MERCHANT_CODE) {
      await Appointment.findByIdAndDelete(createdAppointment._id);
      return res
        .status(500)
        .json({ error: "Payment configuration is missing." });
    }

    const checkoutReference = createdAppointment._id.toString();
    const checkout = await sumupClient.checkouts.create({
      checkout_reference: checkoutReference,
      amount: amountCharged,
      currency: "EUR",
      merchant_code: process.env.SUMUP_MERCHANT_CODE,
      description: `Aanbetaling + servicekosten PrimeCuts afspraak ${service} op ${date} om ${time} (aanbetaling €${formatEuro(depositAmount)} + €${formatEuro(checkoutFee)} servicekosten, rest in winkel)`,
      return_url: getPaymentReturnUrl(req),
      redirect_url: getPaymentRedirectUrl(req, checkoutReference),
      hosted_checkout: { enabled: true },
      valid_until: new Date(Date.now() + 10 * 60 * 1000).toISOString(),
    });

    await Appointment.findByIdAndUpdate(createdAppointment._id, {
      sumupCheckoutId: checkout.id || null,
      sumupCheckoutReference: checkout.checkout_reference || checkoutReference,
    });

    const paymentUrl = checkout.hosted_checkout_url || checkout.redirect_url;
    if (!paymentUrl) {
      throw new Error("SumUp did not return a hosted checkout URL.");
    }

    res.status(201).json({
      success: true,
      appointmentId: createdAppointment._id,
      checkoutId: checkout.id,
      paymentUrl,
      message: "Payment checkout created.",
    });
  } catch (error) {
    console.error("Booking Error:", error);
    if (createdAppointment) {
      await Appointment.findByIdAndDelete(createdAppointment._id).catch(
        () => {},
      );
    }
    res.status(500).json({ error: "Server error while creating appointment" });
  }
};

// How far ahead a new subscription's schedule is checked against existing bookings and other
// subscribers before it's accepted.
const SUBSCRIPTION_CONFLICT_CHECK_DAYS = 365;

// The first occurrence (after the first visit) of a new schedule that collides with an existing
// booking or another subscriber's seat, or null if the whole schedule is free. Without this, two
// subscribers could each pick e.g. Friday 14:00 starting on different weeks (both first visits free)
// and then fight over every Friday after that — or a subscriber could be sold a seat that's already
// booked next week.
const findSubscriptionConflict = async (draft) => {
  const horizon = new Date(Date.now() + SUBSCRIPTION_CONFLICT_CHECK_DAYS * 24 * 60 * 60 * 1000)
    .toISOString()
    .slice(0, 10);
  const dates = [];
  for (let n = 1; ; n++) {
    const date = occurrenceDate(draft, n);
    if (date > horizon) break;
    dates.push(date);
  }

  const bookedDate = await Appointment.findOne({
    date: { $in: dates },
    time: draft.time,
    status: { $in: ["pending", "confirmed"] },
  })
    .sort({ date: 1 })
    .select("date");

  const others = await Subscription.find({ status: { $in: ["pending", "active"] }, time: draft.time });
  const subscriberDate = dates.find((date) =>
    others.some(
      (other) =>
        other.startDate === date || (other.startDate && occurrenceIndexOn(other, date) !== null),
    ),
  );

  const candidates = [bookedDate?.date, subscriberDate].filter(Boolean).sort();
  return candidates[0] || null;
};

// Step 1 of a subscription signup. Validates and reserves the schedule (same checks as a regular
// booking, plus the whole future schedule), holds the first visit, and sets up the card-saving
// checkout. The page then shows SumUp's card form for that checkout; once the customer completes it,
// completeSubscription below charges the first month and confirms everything.
const SETUP_CHECKOUT_VALID_MINUTES = 15;

const createSubscription = async (req, res) => {
  let createdAppointment = null;
  let createdSubscription = null;

  try {
    const { customerName, customerEmail, customerPhone, date, time, frequency } = req.body;

    const customerFieldError = validateCustomerFields(req.body);
    if (customerFieldError) {
      return res.status(400).json({ error: customerFieldError });
    }

    const dateTimeError = validateDateTime(date, time);
    if (dateTimeError) {
      return res.status(400).json({ error: dateTimeError });
    }

    // Reject an unknown plan outright rather than silently falling back to another one — a
    // customer must never be charged for a plan they didn't pick.
    if (typeof frequency !== "string" || !Object.hasOwn(SUBSCRIPTION_PLANS, frequency)) {
      return res.status(400).json({ error: "Onbekend abonnement." });
    }
    // The customer explicitly agreed to the automatic monthly charge (checkbox on the page).
    if (req.body.agreedToMonthlyCharge !== true) {
      return res.status(400).json({ error: "Geef toestemming voor de maandelijkse afschrijving om door te gaan." });
    }
    const plan = frequency;

    const blockedRanges = await BlockedTime.find({ date }).select("startTime endTime -_id");
    if (overlapsBlockedRange(time, blockedRanges)) {
      return res.status(400).json({ error: "Dit tijdslot is niet beschikbaar." });
    }

    const existing = await Appointment.findOne({
      date,
      time,
      status: { $in: ["pending", "confirmed"] },
    });
    // The customer's own unfinished signup (closed the card form, pressed back, double-tapped) is
    // still holding this slot for a few minutes — say so instead of a bare "taken", which reads as if
    // someone else got their seat.
    if (
      existing?.status === "pending" &&
      existing.customerEmail.trim().toLowerCase() === customerEmail.trim().toLowerCase()
    ) {
      return res.status(409).json({
        error:
          "Je hebt voor deze plek al een aanmelding gestart. Rond die af, of probeer het over 20 minuten opnieuw als je die hebt afgebroken.",
      });
    }
    if (existing || (await isReservedBySubscription(date, time))) {
      return res.status(400).json({ error: "Dit tijdslot is al bezet. Kies een ander tijdstip." });
    }

    const dayOfMonth = Number(date.slice(8, 10));
    const draft = { frequency: plan, startDate: date, dayOfMonth, time };

    const conflictDate = await findSubscriptionConflict(draft);
    if (conflictDate) {
      return res.status(400).json({
        error: `Deze vaste plek is niet elke keer vrij — op ${formatDateNl(conflictDate)} om ${time} is hij al bezet. Kies een andere dag of tijd.`,
      });
    }

    if (!process.env.SUMUP_API_KEY || !process.env.SUMUP_MERCHANT_CODE) {
      return res.status(500).json({ error: "Payment configuration is missing." });
    }

    createdSubscription = await Subscription.create({
      customerName,
      customerEmail,
      customerPhone,
      frequency: plan,
      startDate: date,
      dayOfMonth,
      time,
      price: SUBSCRIPTION_PLANS[plan].monthlyPrice,
      firstMonthAmount: firstMonthAmount(draft),
      status: "pending",
    });

    try {
      createdAppointment = await Appointment.create({
        customerName,
        customerEmail,
        customerPhone,
        service: "Abonnement",
        addons: [],
        date,
        time,
        // Paid for by the subscription's first-month charge, not per visit.
        totalPrice: 0,
        depositAmount: 0,
        checkoutFee: 0,
        status: "pending",
        paymentProvider: "subscription",
        subscriptionId: createdSubscription._id,
        subscriptionOccurrenceDate: date,
      });
    } catch (createError) {
      if (createError.code === 11000) {
        await Subscription.findByIdAndDelete(createdSubscription._id);
        return res.status(400).json({ error: "Dit tijdslot is al bezet. Kies een ander tijdstip." });
      }
      throw createError;
    }

    const customerId = await sumupRecurring.createCustomer(createdSubscription);
    const setupCheckout = await sumupRecurring.createCardSetupCheckout({
      subscriptionId: createdSubscription._id,
      customerId,
      amount: BILLING.cardCheckAmount,
      validMinutes: SETUP_CHECKOUT_VALID_MINUTES,
    });

    await Subscription.updateOne(
      { _id: createdSubscription._id },
      {
        $set: {
          firstAppointmentId: createdAppointment._id,
          sumupCustomerId: customerId,
          setupCheckoutId: setupCheckout.id,
        },
      },
    );

    res.status(201).json({
      success: true,
      subscriptionId: createdSubscription._id,
      checkoutId: setupCheckout.id,
      firstMonthAmount: createdSubscription.firstMonthAmount,
      monthlyPrice: createdSubscription.price,
    });
  } catch (error) {
    console.error("Subscription booking error:", error);
    if (createdAppointment) {
      await Appointment.findByIdAndDelete(createdAppointment._id).catch(() => {});
    }
    if (createdSubscription) {
      await Subscription.findByIdAndDelete(createdSubscription._id).catch(() => {});
    }
    res.status(500).json({ error: "Server error while creating subscription" });
  }
};

// Step 2: the page calls this as soon as SumUp's card form reports success. Saves the card, charges
// the first month and confirms the subscription (see completeSignup). The same thing also runs in
// the background (reconcilePendingSignups) in case the page never gets here.
const completeSubscription = async (req, res) => {
  try {
    const { subscriptionId } = req.params;
    if (!isValidObjectId(subscriptionId)) {
      return res.status(400).json({ error: "Ongeldig abonnement." });
    }
    const result = await completeSignup(subscriptionId);
    if (result.status === "active") {
      const subscription = result.subscription;
      return res.status(200).json({
        success: true,
        status: "active",
        data: {
          frequency: subscription.frequency,
          startDate: subscription.startDate,
          time: subscription.time,
          firstMonthAmount: subscription.firstMonthAmount,
          monthlyPrice: subscription.price,
          cardLast4: subscription.cardLast4 || null,
          nextChargeDate: `${nextPeriod(subscription.paidThrough)}-01`,
        },
      });
    }
    res.status(200).json({ success: result.status !== "failed", status: result.status, error: result.error });
  } catch (error) {
    console.error("Subscription completion error:", error);
    res.status(500).json({ error: "Kon de betaling niet controleren. Probeer het zo opnieuw." });
  }
};

// The customer closed the card form ("Annuleren") — release the held seat right away instead of
// making them wait for the signup timeout before they can try again. Only ever touches a signup that
// isn't paid yet (expireSignup only acts on "pending"), so it can't undo a real subscription. If the
// card step had actually just completed, completeSignup is tried first so a paid signup still goes
// through.
const abandonSubscription = async (req, res) => {
  try {
    const { subscriptionId } = req.params;
    if (!isValidObjectId(subscriptionId)) {
      return res.status(400).json({ error: "Ongeldig abonnement." });
    }
    const result = await completeSignup(subscriptionId);
    if (result.status === "pending") {
      const subscription = await Subscription.findById(subscriptionId);
      if (subscription) await expireSignup(subscription);
      return res.status(200).json({ success: true, status: "cancelled" });
    }
    res.status(200).json({ success: true, status: result.status === "active" ? "active" : "cancelled" });
  } catch (error) {
    console.error("Subscription abandon error:", error);
    res.status(500).json({ error: "Annuleren mislukt." });
  }
};

